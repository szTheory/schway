// phase31ControlCopy copies examples/checksum into a TempDir so a source mutant
// never touches the tree.
func phase31ControlCopy(t *testing.T) string {
	t.Helper()
	src := testsupport.ProjectPath("examples", "checksum")
	dst := t.TempDir()
	entries, err := os.ReadDir(src)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		data, err := os.ReadFile(filepath.Join(src, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dst, e.Name()), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dst
}

// phase31ControlBuild builds the checksum entry of dir under flags. Seam users
// must never be parallel.
func phase31ControlBuild(t *testing.T, dir string, flags []string) string {
	t.Helper()
	restore := native.SetApplicationFlagsForTest(flags)
	defer restore()
	artifact := filepath.Join(t.TempDir(), "checksum")
	entry := filepath.Join(dir, "checksum.schway")
	manifest := filepath.Join(dir, "file_bytes.bindings.json")
	_, diagnostics, err := session.BuildApplicationFile(context.Background(), entry, artifact, native.DefaultRunner(), manifest)
	if err != nil || len(diagnostics) != 0 {
		t.Fatalf("build %s with %v: diagnostics=%+v err=%v", entry, flags, diagnostics, err)
	}
	return artifact
}

func phase31ControlFlags(extra ...string) []string {
	return append(append(append([]string(nil), phase29BaseFlags...), "-O0"), extra...)
}

// phase31ControlRow is a pinned oracle row used by the mutant checks.
type phase31ControlRow struct {
	name  string
	input []byte
	want  string
}

func phase31ControlRows(t *testing.T, names ...string) []phase31ControlRow {
	t.Helper()
	var out []phase31ControlRow
	for _, name := range names {
		found := false
		for _, row := range testsupport.ChecksumOracleRows() {
			if row.App == "checksum" && row.Name == name && row.Outcome == "returned" {
				out = append(out, phase31ControlRow{name, row.Input, strconv.FormatUint(row.Want, 10) + "\n"})
				found = true
			}
		}
		if !found {
			t.Fatalf("no checksum oracle row %q", name)
		}
	}
	return out
}

func phase31ControlWrite(t *testing.T, data []byte) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "input.bin")
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func phase31ControlNative(t *testing.T, artifact string, input []byte) (native.RunOutcome, string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	outcome, err := native.RunApplication(context.Background(), artifact, phase31ControlWrite(t, input), &stdout, &stderr)
	if err != nil {
		t.Fatal(err)
	}
	return outcome, stdout.String(), stderr.String()
}

func phase31ControlInterp(t *testing.T, dir string, input []byte) interp.Execution {
	t.Helper()
	checked, err := session.CheckFile(filepath.Join(dir, "checksum.schway"))
	if err != nil || len(checked.Diagnostics) != 0 {
		t.Fatalf("check mutant: %+v %v", checked.Diagnostics, err)
	}
	run, err := interp.RunWithFileBytes(checked.Program, "main", phase31ControlWrite(t, input), testsupport.ChecksumReadFile)
	if err != nil {
		t.Fatal(err)
	}
	return run
}

// phase31ControlMutateLibrary applies mutate to the adler32 library copy.
func phase31ControlMutateLibrary(t *testing.T, dir string, mutate func(string) string) {
	t.Helper()
	path := filepath.Join(dir, "adler32.schway")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	mutated := mutate(string(data))
	if mutated == string(data) {
		t.Fatal("mutant equals the original library")
	}
	if err := os.WriteFile(path, []byte(mutated), 0o600); err != nil {
		t.Fatal(err)
	}
}

// phase31ControlOffByOne makes the loop run one iteration too many. The language
// has no <= operator, so the bound n becomes n + 1 (the same i <= n behavior).
func phase31ControlOffByOne(t *testing.T, s string) string {
	t.Helper()
	return phase29ReplaceOnce(t, s, "var n = byte_len(bytes)\n", "var n = byte_len(bytes)\n  n = n + 1\n")
}

// phase31ControlBoundsCheck matches the generated byte-index bounds block.
var phase31ControlBoundsCheck = regexp.MustCompile(`  if \(\w+ >= \w+\.length\) \{\n    fputs\("schway: byte index out of bounds\\n", stderr\);\n    exit\(65\);\n  \}\n`)

func TestPhase31Controls(t *testing.T) {
	phase29RequireClang(t)
	rows := phase31ControlRows(t, "Wikipedia", "65536x0xFF")
	signed := phase31ControlRows(t, "0x80", "0x80 0xFF", "65536x0xFF")

	// answersDiffer reports whether the engine disagrees with any pinned row.
	nativeDiffers := func(t *testing.T, artifact string, rs []phase31ControlRow) bool {
		differs := false
		for _, r := range rs {
			outcome, stdout, _ := phase31ControlNative(t, artifact, r.input)
			d := outcome.Kind != native.RunExited || outcome.ExitCode != 0 || stdout != r.want
			t.Logf("native %s: exit=%d stdout=%q want=%q differs=%v", r.name, outcome.ExitCode, stdout, r.want, d)
			differs = differs || d
		}
		return differs
	}
	interpDiffers := func(t *testing.T, dir string, rs []phase31ControlRow) bool {
		differs := false
		for _, r := range rs {
			run := phase31ControlInterp(t, dir, r.input)
			d := run.Outcome.Kind != execution.OutcomeReturned || run.Outcome.Value+"\n" != r.want
			t.Logf("interpreter %s: %s %q want=%q differs=%v", r.name, run.Outcome.Kind, run.Outcome.Value, r.want, d)
			differs = differs || d
		}
		return differs
	}

	t.Run("control", func(t *testing.T) {
		dir := phase31ControlCopy(t)
		artifact := phase31ControlBuild(t, dir, phase31ControlFlags())
		all := phase31ControlRows(t, "Wikipedia", "0x80", "0x80 0xFF", "65536x0xFF")
		if nativeDiffers(t, artifact, all) {
			t.Fatal("unmutated native build disagrees with the oracle rows")
		}
		if interpDiffers(t, dir, all) {
			t.Fatal("unmutated interpreter disagrees with the oracle rows")
		}
	})

	sourceMutants := []struct {
		name   string
		mutate func(t *testing.T, s string) string
	}{
		{"wrong-modulus", func(t *testing.T, s string) string {
			s = phase29ReplaceOnce(t, s, "a = a % 65521", "a = a % 65520")
			return phase29ReplaceOnce(t, s, "b = b % 65521", "b = b % 65520")
		}},
		{"wrong-initial-state", func(t *testing.T, s string) string {
			return phase29ReplaceOnce(t, s, "var a = 1\n", "var a = 0\n")
		}},
		{"swapped-halves", func(t *testing.T, s string) string {
			s = phase29ReplaceOnce(t, s, "var r = b", "var r = a")
			return phase29ReplaceOnce(t, s, "r = r + a", "r = r + b")
		}},
	}
	for _, m := range sourceMutants {
		t.Run(m.name, func(t *testing.T) {
			dir := phase31ControlCopy(t)
			phase31ControlMutateLibrary(t, dir, func(s string) string { return m.mutate(t, s) })
			artifact := phase31ControlBuild(t, dir, phase31ControlFlags())
			if !nativeDiffers(t, artifact, rows) {
				t.Fatalf("%s survived on native", m.name)
			}
			if !interpDiffers(t, dir, rows) {
				t.Fatalf("%s survived on the interpreter", m.name)
			}
		})
	}

	t.Run("off-by-one-loop-bound", func(t *testing.T) {
		dir := phase31ControlCopy(t)
		phase31ControlMutateLibrary(t, dir, func(s string) string {
			return phase31ControlOffByOne(t, s)
		})
		artifact := phase31ControlBuild(t, dir, phase31ControlFlags())
		wiki := rows[0].input
		outcome, stdout, stderr := phase31ControlNative(t, artifact, wiki)
		if outcome.Kind != native.RunExited || outcome.ExitCode != 65 || stdout != "" || stderr != phase29OOBStderr {
			t.Fatalf("native outcome=%+v stdout=%q stderr=%q, want exit 65, empty stdout, %q", outcome, stdout, stderr, phase29OOBStderr)
		}
		run := phase31ControlInterp(t, dir, wiki)
		if run.Outcome.Kind != execution.OutcomeDefect || len(run.Events) == 0 {
			t.Fatalf("interpreter outcome=%+v, want a defect", run.Outcome)
		}
		if final := run.Events[len(run.Events)-1]; final.Kind != "function.defected" || final.Output != "byte index out of bounds" {
			t.Fatalf("interpreter final event = %+v, want the byte index defect", final)
		}
	})

	t.Run("signed-char-retype", func(t *testing.T) {
		restoreMutation := native.SetApplicationCSourceMutationForTest(phase29SignedCharMutation(t))
		defer restoreMutation()
		dir := phase31ControlCopy(t)
		artifact := phase31ControlBuild(t, dir, phase31ControlFlags())
		if !nativeDiffers(t, artifact, signed) {
			t.Fatal("signed-char retype mutant survived the 0x80 / 0xFF rows")
		}
	})

	t.Run("signed-char-flag-lane", func(t *testing.T) {
		dir := phase31ControlCopy(t)
		artifact := phase31ControlBuild(t, dir, phase31ControlFlags("-fsigned-char"))
		if nativeDiffers(t, artifact, signed) {
			t.Fatal("-fsigned-char lane disagrees with the oracle: the program depends on platform char signedness")
		}
	})

	t.Run("deleted-bounds-check-asan", func(t *testing.T) {
		phase29RequireASan(t)
		t.Setenv("ASAN_OPTIONS", phase29LeakOption(0))
		restoreMutation := native.SetApplicationCSourceMutationForTest(func(c string) string {
			if got := len(phase31ControlBoundsCheck.FindAllString(c, -1)); got != 1 {
				t.Fatalf("emitted C has %d bounds-check blocks, want exactly 1", got)
			}
			return phase31ControlBoundsCheck.ReplaceAllString(c, "")
		})
		defer restoreMutation()
		dir := phase31ControlCopy(t)
		phase31ControlMutateLibrary(t, dir, func(s string) string {
			return phase31ControlOffByOne(t, s)
		})
		flags := phase31ControlFlags("-fsanitize=address", "-fno-sanitize-ignorelist", "-fno-omit-frame-pointer")
		artifact := phase31ControlBuild(t, dir, flags)
		_, _, stderr := phase31ControlNative(t, artifact, rows[0].input)
		if !strings.Contains(stderr, "AddressSanitizer: heap-buffer-overflow") {
			t.Fatalf("stderr does not report AddressSanitizer: heap-buffer-overflow:\n%s", stderr)
		}
		if strings.Contains(stderr, "schway: byte index out of bounds") {
			t.Fatalf("the checked failure fired although the bounds check was deleted:\n%s", stderr)
		}
	})
}
